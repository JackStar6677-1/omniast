"""
Java 21/25 Transpiler for OmniAST (Paper / Spigot / JVM)
"""

from core.kernel.engine import OmniASTModule

EVENT_MAPPINGS = {
    "player.chat": ("org.bukkit.event.player.AsyncChatEvent", "AsyncChatEvent"),
    "player.join": ("org.bukkit.event.player.PlayerJoinEvent", "PlayerJoinEvent"),
    "player.quit": ("org.bukkit.event.player.PlayerQuitEvent", "PlayerQuitEvent"),
    "player.interact": ("org.bukkit.event.player.PlayerInteractEvent", "PlayerInteractEvent"),
    "block.break": ("org.bukkit.event.block.BlockBreakEvent", "BlockBreakEvent"),
    "block.place": ("org.bukkit.event.block.BlockPlaceEvent", "BlockPlaceEvent"),
    "inventory.click": ("org.bukkit.event.inventory.InventoryClickEvent", "InventoryClickEvent"),
    "generic": ("org.bukkit.event.Event", "Event"),
}

class JavaTranspiler:
    def emit(self, module: OmniASTModule) -> str:
        # Collect dynamic imports based on node events
        needed_imports = set([
            "org.bukkit.plugin.java.JavaPlugin",
            "org.bukkit.event.Listener",
            "org.bukkit.event.EventHandler",
            "org.bukkit.event.EventPriority",
        ])

        for node in module.nodes:
            if node.type == "listener":
                evt_name = node.metadata.get("event", "player.chat").lower()
                imp_class, _ = EVENT_MAPPINGS.get(evt_name, ("org.bukkit.event.Event", "Event"))
                needed_imports.add(imp_class)

        imports_code = sorted(list(needed_imports))

        code = [
            "// Auto-generated by OmniAST Kernel Transpiler (JVM Target)",
            "// Target Platform: Paper 1.21.11 / Purpur 26.x (Java 21+)",
            f"package org.omniast.generated.{module.name.lower()};",
            "",
        ]
        for imp in imports_code:
            code.append(f"import {imp};")
        code.append("")

        code.extend([
            f"public final class {module.name}Plugin extends JavaPlugin implements Listener {{",
            "",
            "    @Override",
            "    public void onEnable() {",
            "        getServer().getPluginManager().registerEvents(this, this);",
            f"        getLogger().info(\"[{module.name}] Initialized via OmniAST Kernel v{module.version}\");",
            "        startOmniTasks();",
            "    }",
            "",
            "    private void startOmniTasks() {",
        ])

        # Task initiation for machines & sentinels
        for node in module.nodes:
            if node.type in ("machine", "sentinel"):
                code.append(f"        getLogger().info(\"[{module.name}] Starting {node.type} task: {node.name}\");")
        code.extend([
            "    }",
            ""
        ])

        for node in module.nodes:
            if node.type == "listener":
                evt_name = node.metadata.get("event", "player.chat").lower()
                _, simple_class = EVENT_MAPPINGS.get(evt_name, ("org.bukkit.event.Event", "Event"))
                priority = node.metadata.get("priority", "NORMAL").upper()
                if priority not in ("LOWEST", "LOW", "NORMAL", "HIGH", "HIGHEST", "MONITOR"):
                    priority = "NORMAL"

                code.extend([
                    f"    @EventHandler(priority = EventPriority.{priority})",
                    f"    public void on{node.name}({simple_class} event) {{",
                    f"        // OmniAST Guard: {node.metadata.get('guard', 'true')}",
                    f"        // Event type: {evt_name}",
                    "        // Generated safety logic",
                    "    }",
                    ""
                ])

        code.append("}")
        return "\n".join(code)
